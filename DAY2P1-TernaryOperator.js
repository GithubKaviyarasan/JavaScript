// // 5.Ternary Operator
// // ---------------------
// // The Ternary Operator is a shorthand form of if...else.

// // It checks a condition and returns one value if the condition is true 
// // and another value if it is false.

// // Syntax:
// // -------
// condition ? statement1 : statement2;

// // Formula:
// // --------
// Condition ?
//     True Statement
//     :
//     False Statement


// // Example Programs
// // -----------------

// // 1.Voting Eligibility
// // --------------------
