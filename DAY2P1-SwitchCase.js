// // 6.Switch Case
// // -------------
// // Switch Case is a decision-making statement used to execute different blocks of code 
// // based on different values of an expression.

// // It is an alternative to multiple if...else if statements.

// // Syntax:
// // ----------
// // switch(expression) {

//     case value1:
//         // code
//         break;

//     case value2:
//         // code
//         break;

//     case value3:
//         // code
//         break;

//     default:
//         // code
// }


